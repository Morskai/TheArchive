fn setup() -> (tempfile::TempDir, Storage, PathBuf) {
    let home = tempfile::tempdir().unwrap();
    let root = home.path().join("synthetic-library");
    fs::create_dir_all(root.join("[TEST-01] 虚构影片")).unwrap();
    fs::write(root.join("[TEST-01] 虚构影片/first.mp4"), []).unwrap();
    let storage = Storage::open(&home.path().join("software")).unwrap();
    storage
        .with_connection(|db| {
            db.execute(
                "INSERT INTO libraries(id,display_name,root_path) VALUES('test','隔离来源',?1)",
                [root.to_string_lossy().as_ref()],
            )?;
            Ok(())
        })
        .unwrap();
    (home, storage, root)
}
fn scan(storage: &Storage, root: &Path) {
    assert!(matches!(
        scan_into_library(storage, "test", root).unwrap(),
        ScanResult::Complete(_)
    ));
}
fn generated(storage: &Storage) -> PathBuf {
    let cache = storage.data_directory().join("cover-cache");
    fs::create_dir_all(&cache).unwrap();
    let file = cache.join(format!("v1-{}-480.jpg", "a".repeat(64)));
    fs::write(&file, b"synthetic generated bytes").unwrap();
    file
}
fn manual(storage: &Storage) -> String {
    let film = catalog::list_films(storage).unwrap().remove(0);
    storage.with_connection(|db| {
        db.execute("INSERT INTO film_manual(film_id,title,code,rating,favorite,cover_choice) VALUES(?1,'人工片名','TEST-01',8,1,'legacy')",[&film.id])?;
        db.execute("INSERT INTO actors(id,observed_name) VALUES('actor','虚构演员')",[])?;
        db.execute("INSERT INTO actor_manual(actor_id,favorite,height_cm) VALUES('actor',1,165)",[])?;
        db.execute("INSERT INTO film_actors(film_id,actor_id,source) VALUES(?1,'actor','manual')",[&film.id])?;
        db.execute("INSERT INTO tags(id,name) VALUES('tag','人工标签')",[])?;
        db.execute("INSERT INTO film_tags(film_id,tag_id) VALUES(?1,'tag')",[&film.id])?;
        db.execute("INSERT INTO file_versions(observation_id,preferred) VALUES(?1,1)",[&film.videos[0].id])?;
        db.execute("INSERT INTO player_launch_events(id,film_id,observation_id,launched_at) VALUES('event',?1,?2,'2026-10-04T10:00:00Z')",(&film.id,&film.videos[0].id))?;
        db.execute("UPDATE issue_records SET handled_at=CURRENT_TIMESTAMP,resolution='marked' WHERE subject_type='film_missing_cover'",[])?;
        db.execute("INSERT INTO player_settings(singleton,mode,program,arguments) VALUES(1,'system','','synthetic')",[])?;
        Ok(())
    }).unwrap();
    film.id
}

#[test]
fn interface_preferences_survive_reopen_and_backup_restore_and_failed_write_rolls_back() {
    let (home, storage, _root) = setup();
    assert_eq!(
        lifecycle::load_preferences(&storage).unwrap(),
        InterfacePreferences {
            reduce_motion: false,
            thin_scrollbar: true,
            ..InterfacePreferences::default()
        }
    );
    let preferences = InterfacePreferences {
        reduce_motion: true,
        thin_scrollbar: false,
        ..InterfacePreferences::default()
    };
    lifecycle::save_preferences(&storage, &preferences).unwrap();
    let backup = storage.create_backup().unwrap();
    drop(storage);
    let storage = Storage::open(&home.path().join("software")).unwrap();
    assert_eq!(lifecycle::load_preferences(&storage).unwrap(), preferences);
    storage.with_connection(|db|db.execute_batch("CREATE TRIGGER reject_preferences BEFORE UPDATE ON interface_preferences BEGIN SELECT RAISE(ABORT,'synthetic'); END;")).unwrap();
    assert!(lifecycle::save_preferences(
        &storage,
        &InterfacePreferences {
            reduce_motion: false,
            thin_scrollbar: true,
            ..InterfacePreferences::default()
        }
    )
    .is_err());
    assert_eq!(lifecycle::load_preferences(&storage).unwrap(), preferences);
    storage.restore_backup(&backup).unwrap();
    assert_eq!(lifecycle::load_preferences(&storage).unwrap(), preferences);
}

#[test]
fn restore_initial_state_clears_library_manual_values_settings_and_cache_but_keeps_originals_and_backups() {
    let (_home, storage, root) = setup();
    let original = root.join("[TEST-01] 虚构影片/first.mp4");
    fs::write(&original, b"synthetic original media").unwrap();
    let external_info = root.join("[TEST-01] 虚构影片/actor.info");
    fs::write(&external_info, b"synthetic external actor info").unwrap();
    scan(&storage, &root);
    manual(&storage);
    storage.with_connection(|db| {
        db.execute("INSERT INTO actor_tags(name,position) VALUES('演员标签',0)", [])?;
        db.execute("INSERT INTO actor_tag_links(actor_id,tag) VALUES('actor','演员标签')", [])?;
        Ok(())
    }).unwrap();
    scan_rules::save(&storage, &["photos".into()]).unwrap();
    lifecycle::save_preferences(
        &storage,
        &InterfacePreferences {
            reduce_motion: true,
            thin_scrollbar: false,
            ..InterfacePreferences::default()
        },
    )
    .unwrap();
    let backup = storage.create_backup().unwrap();
    let backup_path = storage.data_directory().join(format!("backups/backup-{backup}.sqlite3"));
    let backup_bytes = fs::read(&backup_path).unwrap();
    let cache = generated(&storage);
    reset::restore_initial_state_with(&storage, &mut empty_credentials::EmptyCredentials::default()).unwrap();
    storage.with_connection(|db| {
        for table in ["libraries","films","film_aliases","file_observations","film_manual","actors","actor_manual","film_actors","actor_image_sources","film_tags","tags","actor_tags","actor_tag_links","player_launch_events","file_versions","issue_records","ignored_directory_names"] {
            let count:i64=db.query_row(&format!("SELECT COUNT(*) FROM {table}"),[],|r|r.get(0))?;assert_eq!(count,0,"{table}");
        }
        Ok(())
    }).unwrap();
    assert!(catalog::list_films(&storage).unwrap().is_empty());
    assert_eq!(lifecycle::load_preferences(&storage).unwrap(), InterfacePreferences::default());
    assert_eq!(playback::load_settings(&storage).unwrap(), playback::PlayerSettings::default());
    assert!(scan_rules::load(&storage).unwrap().is_empty());
    assert_eq!(storage.list_backups().unwrap().len(), 1);
    assert_eq!(fs::read(&backup_path).unwrap(), backup_bytes);
    assert!(!cache.exists());
    assert!(!storage.data_directory().join("cover-cache").exists());
    assert!(!storage.data_directory().join("protections").exists());
    assert_eq!(fs::read(original).unwrap(), b"synthetic original media");
    assert_eq!(fs::read(external_info).unwrap(), b"synthetic external actor info");
}

#[test]
fn restore_initial_state_sql_or_protection_failure_keeps_database_manual_values_and_cache() {
    for sql_failure in [true, false] {
        let (_home, storage, root) = setup();
        scan(&storage, &root);
        manual(&storage);
        let cache = generated(&storage);
        if sql_failure {
            storage.with_connection(|db|db.execute_batch("CREATE TRIGGER reject_clear BEFORE DELETE ON actor_manual BEGIN SELECT RAISE(ABORT,'synthetic'); END;")).unwrap();
        } else {
            let protections = storage.data_directory().join("protections");
            fs::remove_dir_all(&protections).unwrap();
            fs::write(&protections, b"synthetic blocker").unwrap();
        }
        let database_path = storage.data_directory().join("library.sqlite3");
        let database_bytes = fs::read(&database_path).unwrap();
        assert!(reset::restore_initial_state_with(&storage, &mut empty_credentials::EmptyCredentials::default()).is_err());
        assert_eq!(fs::read(database_path).unwrap(), database_bytes);
        let saved = catalog::list_films(&storage).unwrap().remove(0);
        assert!(saved.favorite);
        assert_eq!(saved.rating, Some(4.0));
        assert!(saved.last_launched_at.is_some());
        storage.with_connection(|db| {
            assert_eq!(db.query_row::<i64, _, _>("SELECT COUNT(*) FROM player_launch_events", [], |r| r.get(0))?, 1);
            assert_eq!(db.query_row::<(bool, i64), _, _>("SELECT favorite,height_cm FROM actor_manual WHERE actor_id='actor'", [], |r| Ok((r.get(0)?, r.get(1)?)))?, (true, 165));
            Ok(())
        }).unwrap();
        assert_eq!(playback::load_settings(&storage).unwrap().launch_arguments, "synthetic");
        assert!(cache.exists());
    }
}

#[test]
fn clear_generated_cache_only_removes_owned_cache_and_keeps_manual_media_and_backups() {
    let (_home, storage, root) = setup();
    scan(&storage, &root);
    manual(&storage);
    storage.create_backup().unwrap();
    let cache = generated(&storage);
    let unrelated = storage.data_directory().join("cover-cache/unrelated.txt");
    fs::write(&unrelated, b"retain").unwrap();
    lifecycle::clear_generated_cache(&storage).unwrap();
    assert!(!cache.exists());
    assert!(unrelated.exists());
    assert!(catalog::list_films(&storage).unwrap()[0].favorite);
    assert_eq!(storage.list_backups().unwrap().len(), 1);
    assert!(root.join("[TEST-01] 虚构影片/first.mp4").exists());
}

#[test]
fn startup_keeps_saved_records_and_cache_across_new_sessions_even_offline() {
    let (_home, storage, root) = setup();
    scan(&storage, &root);
    let id = manual(&storage);
    let cache = generated(&storage);
    fs::write(root.join("[TEST-01] 虚构影片/new.mkv"), []).unwrap();
    storage.with_connection(|db|db.execute_batch("CREATE TRIGGER reject_startup_scan BEFORE INSERT ON file_observations BEGIN SELECT RAISE(ABORT,'synthetic'); END;")).unwrap();
    let session = StartupSession::default();
    assert_eq!(session.initialize(&storage).unwrap().saved_sources, 1);
    assert_eq!(session.initialize(&storage).unwrap().saved_sources, 1);
    fs::rename(&root, root.with_extension("offline")).unwrap();
    assert_eq!(
        StartupSession::default()
            .initialize(&storage)
            .unwrap()
            .saved_sources,
        1
    );
    let film = catalog::list_films(&storage).unwrap().remove(0);
    assert_eq!(film.id, id);
    assert!(film.favorite);
    assert_eq!(film.videos.len(), 1);
    assert!(cache.exists());
}
#[test]
fn manual_scan_verifies_related_source_and_restores_moves_but_keeps_real_duplicates() {
    for move_file in [false, true] {
        let (home, storage, old_root) = setup();
        scan(&storage, &old_root);
        let old_id = manual(&storage);
        let new_root = home.path().join("synthetic-destination");
        fs::create_dir_all(new_root.join("[TEST-02] 虚构新位置")).unwrap();
        storage.with_connection(|db| {
            db.execute("INSERT INTO libraries(id,display_name,root_path) VALUES('destination','隔离目标',?1)", [new_root.to_string_lossy().as_ref()])?;
            Ok(())
        }).unwrap();
        let target = new_root.join("[TEST-02] 虚构新位置/first.mp4");
        if move_file {
            fs::rename(old_root.join("[TEST-01] 虚构影片/first.mp4"), &target).unwrap();
        } else {
            fs::write(&target, []).unwrap();
        }
        let session = local_film_library_preview_lib::source_scan::SourceScanSession::new();
        let preview = session
            .preview(&storage, &new_root, Some("destination"))
            .unwrap();
        let result =
            lifecycle::confirm_source_refresh(&storage, &session, &preview.token.unwrap()).unwrap();
        assert_eq!(result.related_retained, 0);
        assert!(!result.recovery_failed);
        let films = catalog::list_films(&storage).unwrap();
        assert_eq!(films.len(), if move_file { 1 } else { 2 });
        assert!(
            films
                .iter()
                .find(|film| film.id == old_id)
                .unwrap()
                .favorite
        );
        if !move_file {
            assert!(
                !films
                    .iter()
                    .find(|film| film.id != old_id)
                    .unwrap()
                    .favorite
            );
            fs::remove_file(old_root.join("[TEST-01] 虚构影片/first.mp4")).unwrap();
            StartupSession::default().initialize(&storage).unwrap();
            assert_eq!(catalog::list_films(&storage).unwrap().len(), 2);
        }
    }
}

#[test]
fn manual_scan_coordination_failure_rolls_back_relationships_and_retries_at_next_scan() {
    let (home, storage, old_root) = setup();
    scan(&storage, &old_root);
    let old_id = manual(&storage);
    let new_root = home.path().join("synthetic-destination");
    fs::create_dir_all(new_root.join("[TEST-02] 虚构新位置")).unwrap();
    storage.with_connection(|db| {
        db.execute("INSERT INTO libraries(id,display_name,root_path) VALUES('destination','隔离目标',?1)", [new_root.to_string_lossy().as_ref()])?;
        db.execute_batch("CREATE TRIGGER reject_coordination BEFORE INSERT ON film_aliases BEGIN SELECT RAISE(ABORT,'synthetic'); END;")?;
        Ok(())
    }).unwrap();
    fs::rename(
        old_root.join("[TEST-01] 虚构影片/first.mp4"),
        new_root.join("[TEST-02] 虚构新位置/first.mp4"),
    )
    .unwrap();
    let session = local_film_library_preview_lib::source_scan::SourceScanSession::new();
    let preview = session
        .preview(&storage, &new_root, Some("destination"))
        .unwrap();
    let result =
        lifecycle::confirm_source_refresh(&storage, &session, &preview.token.unwrap()).unwrap();
    assert!(result.recovery_failed);
    assert_ne!(catalog::list_films(&storage).unwrap()[0].id, old_id);
    storage
        .with_connection(|db| {
            assert_eq!(
                db.query_row::<i64, _, _>("SELECT COUNT(*) FROM film_aliases", [], |r| r.get(0))?,
                0
            );
            assert_eq!(
                db.query_row::<i64, _, _>(
                    "SELECT favorite FROM film_manual WHERE film_id=?1",
                    [&old_id],
                    |r| r.get(0)
                )?,
                1
            );
            db.execute_batch("DROP TRIGGER reject_coordination")?;
            Ok(())
        })
        .unwrap();
    let summary = StartupSession::default().initialize(&storage).unwrap();
    assert_eq!(summary.saved_sources, 2);
    assert_ne!(catalog::list_films(&storage).unwrap()[0].id, old_id);
    let preview = session
        .preview(&storage, &new_root, Some("destination"))
        .unwrap();
    let result =
        lifecycle::confirm_source_refresh(&storage, &session, &preview.token.unwrap()).unwrap();
    assert!(!result.recovery_failed);
    assert_eq!(catalog::list_films(&storage).unwrap()[0].id, old_id);
    assert!(catalog::list_films(&storage).unwrap()[0].favorite);
}
